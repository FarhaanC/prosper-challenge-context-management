"""Fake, repeatable appointment availability, in clinic time.

The brief says availability isn't provided, and our tests must give the same
answer every run, so open times are generated by a fixed recipe:

- A doctor who works at several locations is at ONE location per weekday
  (rotating through their sites), so they can't be double-booked across sites.
  (With 5 working days, this suits doctors with up to 5 sites; the catalog's
  maximum is 4.)
- The day is cut into 30-minute blocks within the location's opening hours,
  with lunch (12:00-13:00) blocked.
- About half the blocks are already "taken". Which ones is decided by a
  sha256 hash of (doctor, location, date, block), so the same date always looks
  the same, in every run and on every computer.
- A visit needs enough free blocks in a row for its length (a 45-minute visit
  needs two), must finish by closing time, and must start at least 2 hours from now.
- Times are offered for today plus the next 14 days.
- Bookings made through our agent are remembered and removed from what's offered.

All times are "clinic time": San Francisco local time, without a time-zone label.
Code that needs the current time must use `clinic_now()`, never `datetime.now()`,
because the computer running the agent may be anywhere (e.g. Dubai, 11 hours ahead).
"""

from __future__ import annotations

import hashlib
from datetime import date, datetime, time, timedelta
from typing import Iterator, Optional

from .catalog import Catalog

CLINIC_TIME_ZONE = "America/Los_Angeles"
BLOCK_MIN = 30
LUNCH = (time(12, 0), time(13, 0))
TAKEN_PERCENT = 50   # share of blocks already booked by other patients (keeps the calendar realistic)
DAYS_AHEAD = 14      # offer today plus this many days
MIN_NOTICE = timedelta(hours=2)  # don't book someone in for 10 minutes from now


class SlotTaken(ValueError):
    """Raised when booking a time that isn't free."""


def clinic_now() -> datetime:
    """The current time at the clinics (San Francisco), as a plain datetime.

    Needs the IANA time-zone data. Linux and macOS have it built in; on Windows
    install the small `tzdata` package (it's in requirements.txt).
    """
    from zoneinfo import ZoneInfo

    return datetime.now(ZoneInfo(CLINIC_TIME_ZONE)).replace(tzinfo=None, second=0, microsecond=0)


def _stable_int(*parts) -> int:
    return int(hashlib.sha256("|".join(map(str, parts)).encode()).hexdigest()[:8], 16)


def blocks_needed(duration_min: int) -> int:
    return max(1, -(-duration_min // BLOCK_MIN))  # round up: 45 min -> 2 blocks


class Schedule:
    def __init__(self, catalog: Catalog, booked: Optional[set] = None):
        self.catalog = catalog
        self._generated: dict = {}  # (provider, location, date) -> free blocks before our bookings
        self._booked: dict = {}     # provider -> list of (start, duration_min) booked through our agent
        for provider_id, start, duration in booked or ():
            self._booked.setdefault(provider_id, []).append((start, duration))

    @property
    def booked(self) -> set:
        return {(pid, s, d) for pid, items in self._booked.items() for s, d in items}

    def location_on(self, provider_id: str, day: date) -> Optional[str]:
        """Which location this doctor works at on this date (None = not working)."""
        sites = sorted(self.catalog.providers[provider_id].location_ids)
        site = sites[(day.weekday() + _stable_int(provider_id)) % len(sites)]
        return site if day.weekday() in self.catalog.locations[site].open_days else None

    def _generated_free(self, provider_id: str, location_id: str, day: date) -> frozenset:
        key = (provider_id, location_id, day)
        if key not in self._generated:
            loc = self.catalog.locations[location_id]
            free = set()
            if self.location_on(provider_id, day) == location_id:
                t, end = datetime.combine(day, loc.opens), datetime.combine(day, loc.closes)
                while t < end:
                    in_lunch = LUNCH[0] <= t.time() < LUNCH[1]
                    taken = _stable_int(provider_id, location_id, day.isoformat(), t.strftime("%H%M")) % 100 < TAKEN_PERCENT
                    if not in_lunch and not taken:
                        free.add(t)
                    t += timedelta(minutes=BLOCK_MIN)
            self._generated[key] = frozenset(free)
        return self._generated[key]

    def _free_blocks(self, provider_id: str, location_id: str, day: date) -> set:
        free = set(self._generated_free(provider_id, location_id, day))
        for start, duration in self._booked.get(provider_id, ()):
            if start.date() == day:
                for k in range(blocks_needed(duration)):
                    free.discard(start + timedelta(minutes=BLOCK_MIN * k))
        return free

    def _starts_on(self, provider_id: str, location_id: str, duration_min: int, day: date, now: datetime) -> list:
        free = self._free_blocks(provider_id, location_id, day)
        if not free:
            return []
        closes = self.catalog.locations[location_id].closes
        need = blocks_needed(duration_min)
        out = []
        for start in sorted(free):
            if start < now + MIN_NOTICE:
                continue
            finish = start + timedelta(minutes=duration_min)
            run = (start + timedelta(minutes=BLOCK_MIN * k) for k in range(need))
            if finish.date() == day and finish.time() <= closes and all(b in free for b in run):
                out.append(start)
        return out

    def iter_open_slots(self, provider_id: str, location_id: str, duration_min: int, now: datetime,
                        days_ahead: int = DAYS_AHEAD) -> Iterator[datetime]:
        """Open start times in time order, worked out one day at a time (so a search
        that only needs the first few never computes the whole fortnight)."""
        for offset in range(days_ahead + 1):
            yield from self._starts_on(provider_id, location_id, duration_min, now.date() + timedelta(days=offset), now)

    def open_slots(self, provider_id: str, location_id: str, duration_min: int, now: datetime,
                   days_ahead: int = DAYS_AHEAD) -> list:
        return list(self.iter_open_slots(provider_id, location_id, duration_min, now, days_ahead))

    def is_open(self, provider_id: str, location_id: str, duration_min: int, start: datetime, now: datetime) -> bool:
        if not (now.date() <= start.date() <= now.date() + timedelta(days=DAYS_AHEAD)):
            return False
        return start in self._starts_on(provider_id, location_id, duration_min, start.date(), now)

    def book(self, provider_id: str, start: datetime, duration_min: int) -> None:
        """Remember a booking. Refuses (SlotTaken) if any block it needs is no longer free."""
        location_id = self.location_on(provider_id, start.date())
        free = self._free_blocks(provider_id, location_id, start.date()) if location_id else set()
        if not all(start + timedelta(minutes=BLOCK_MIN * k) in free for k in range(blocks_needed(duration_min))):
            raise SlotTaken(f"{provider_id} is not free at {start:%Y-%m-%d %H:%M} for {duration_min} minutes.")
        self._booked.setdefault(provider_id, []).append((start, duration_min))


def spoken_time(dt: datetime) -> str:
    """'Tuesday 13 October at 9:30 AM': how the agent should say a time."""
    hour = dt.strftime("%I").lstrip("0")
    minutes = dt.strftime("%M")
    clock = f"{hour}:{minutes} {dt.strftime('%p')}" if minutes != "00" else f"{hour} {dt.strftime('%p')}"
    return f"{dt.strftime('%A')} {dt.day} {dt.strftime('%B')} at {clock}"
