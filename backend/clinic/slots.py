"""Fake, repeatable appointment availability.

The brief says availability isn't provided, and our tests must give the same
answer every run, so open times are generated by a fixed recipe:

- A doctor who works at several locations is at ONE location per weekday
  (rotating through their sites), so they can never be double-booked across sites.
- The day is cut into 30-minute blocks within the location's opening hours,
  with lunch (12:00-13:00) blocked.
- About half the blocks are already "taken". Which ones is decided by a hash of
  (doctor, location, date, block), so the same date always looks the same.
- A visit needs enough free blocks in a row for its length (a 45-minute visit
  needs two), and must finish before closing.
- Bookings made through our agent are remembered and removed from what's offered.
"""

from __future__ import annotations

import hashlib
import re
from datetime import date, datetime, time, timedelta
from typing import Optional

from .catalog import Catalog

BLOCK_MIN = 30
LUNCH = (time(12, 0), time(13, 0))
TAKEN_PERCENT = 50
DAYS_AHEAD = 14
MIN_NOTICE = timedelta(hours=2)  # no booking someone in for 10 minutes from now

DAY_NAMES = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]


def _stable_int(*parts) -> int:
    return int(hashlib.sha256("|".join(map(str, parts)).encode()).hexdigest()[:8], 16)


def parse_hours(hours: str) -> tuple:
    """'Mon-Fri 8:00-17:00' -> ({0,1,2,3,4}, time(8,0), time(17,0))."""
    m = re.match(r"(\w{3})-(\w{3})\s+(\d{1,2}):(\d{2})-(\d{1,2}):(\d{2})", hours)
    if not m:
        return set(range(5)), time(8, 0), time(17, 0)
    d1, d2 = DAY_NAMES.index(m.group(1)), DAY_NAMES.index(m.group(2))
    days = set(range(d1, d2 + 1))
    return days, time(int(m.group(3)), int(m.group(4))), time(int(m.group(5)), int(m.group(6)))


class Schedule:
    def __init__(self, catalog: Catalog, booked: Optional[set] = None):
        self.catalog = catalog
        # (provider_id, start datetime, duration_min) booked through our agent.
        self.booked: set = set(booked or ())

    # Which location is this doctor at on this date? (None = not working)
    def location_on(self, provider_id: str, day: date) -> Optional[str]:
        p = self.catalog.providers[provider_id]
        sites = sorted(p.location_ids)
        if not sites:
            return None
        working_days = parse_hours(self.catalog.locations[sites[0]].hours)[0]
        if day.weekday() not in working_days:
            return None
        return sites[(day.weekday() + _stable_int(provider_id)) % len(sites)]

    def _free_blocks(self, provider_id: str, location_id: str, day: date) -> list:
        days, open_t, close_t = parse_hours(self.catalog.locations[location_id].hours)
        if day.weekday() not in days or self.location_on(provider_id, day) != location_id:
            return []
        blocks = []
        t = datetime.combine(day, open_t)
        end = datetime.combine(day, close_t)
        while t < end:
            in_lunch = LUNCH[0] <= t.time() < LUNCH[1]
            taken = _stable_int(provider_id, location_id, day.isoformat(), t.strftime("%H%M")) % 100 < TAKEN_PERCENT
            if not in_lunch and not taken:
                blocks.append(t)
            t += timedelta(minutes=BLOCK_MIN)
        return blocks

    def open_slots(self, provider_id: str, location_id: str, duration_min: int, now: datetime,
                   days_ahead: int = DAYS_AHEAD) -> list:
        """Start times when this doctor can see someone at this location for this long."""
        need = max(1, -(-duration_min // BLOCK_MIN))  # round up
        close_t = parse_hours(self.catalog.locations[location_id].hours)[2]
        ours = [(s, d) for (pid, s, d) in self.booked if pid == provider_id]
        out = []
        for offset in range(days_ahead + 1):
            day = now.date() + timedelta(days=offset)
            free = set(self._free_blocks(provider_id, location_id, day))
            # Blocks covered by bookings made through our agent are no longer free.
            for b_start, b_len in ours:
                if b_start.date() == day:
                    for k in range(max(1, -(-b_len // BLOCK_MIN))):
                        free.discard(b_start + timedelta(minutes=BLOCK_MIN * k))
            for start in sorted(free):
                if start < now + MIN_NOTICE:
                    continue
                run = [start + timedelta(minutes=BLOCK_MIN * k) for k in range(need)]
                finish = start + timedelta(minutes=duration_min)
                if all(b in free for b in run) and finish.time() <= close_t and finish.date() == day:
                    out.append(start)
        return out

    def is_open(self, provider_id: str, location_id: str, duration_min: int, start: datetime, now: datetime) -> bool:
        return start in self.open_slots(provider_id, location_id, duration_min, now)

    def book(self, provider_id: str, start: datetime, duration_min: int) -> None:
        self.booked.add((provider_id, start, duration_min))


def spoken_time(dt: datetime) -> str:
    """'Tuesday 13 October at 9:30 AM' — how the agent should say a slot."""
    hour = dt.strftime("%I").lstrip("0")
    minutes = dt.strftime("%M")
    clock = f"{hour}:{minutes} {dt.strftime('%p')}" if minutes != "00" else f"{hour} {dt.strftime('%p')}"
    return f"{dt.strftime('%A')} {dt.day} {dt.strftime('%B')} at {clock}"
